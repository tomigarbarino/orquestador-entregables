// <Icono de={Plug} />: 16px, trazo 1.75. Con etiqueta se anuncia; sin etiqueta es decorativo.
export function Icono({ de: Componente, tam = 16, className, etiqueta, ...resto }) {
  if (!Componente) return null;
  const clases = ['icono', className].filter(Boolean).join(' ');
  const accesible = etiqueta ? { role: 'img', 'aria-label': etiqueta } : { 'aria-hidden': true, focusable: 'false' };
  return <Componente size={tam} strokeWidth={1.75} className={clases} {...accesible} {...resto} />;
}
